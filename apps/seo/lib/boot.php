<?php

declare(strict_types=1);

// Подключение рабочего слоя раздела «SEO и статистика». Правила нужны при каждом запросе,
// а в боевом процессе их не подключает никто, поэтому require_once здесь — единственная
// точка, где модуль встречается с ядром.
require_once __DIR__ . '/meta.php';

// Метаданные правят собранную страницу: заголовок, описание, канонический адрес и закрытие
// адреса от индексации. Сборщик статистики (S2) подпишется здесь же своим фильтром —
// раздел и статистика живут рядом, но каждый работает сам по себе.
addFilter('page_meta', 'seoMetaPageMeta');

// Адреса, которые человек назвал сам и оставил открытыми, попадают в карту сайта.
addFilter('sitemap_urls', 'seoMetaSitemapUrls');
