<?php

declare(strict_types=1);

// Стартовые значения раздела «SEO и статистика». Ключ подписи счётчика создаётся один раз
// при установке: он нужен и странице (она кладёт подпись в разметку скрипта), и приёмнику
// (он сверяет её). Генерировать его на каждом публичном просмотре — значило бы писать в базу
// на чтении, а это плохая привычка даже для одной записи.
//
// Обновление раздела (1.0.0 → 1.1.0) сид не выполняет: ключ создаётся сам при первом
// обращении к счётчику (см. seoCollectSecret() в lib/stats.php).

if (getOption(SEO_STATS_OPTION_SECRET, '') === '') {
    setOption(SEO_STATS_OPTION_SECRET, bin2hex(random_bytes(32)));
}
