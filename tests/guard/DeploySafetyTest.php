<?php

declare(strict_types=1);

namespace Cms\Tests\guard;

use PHPUnit\Framework\TestCase;

// Выкладка — единственное место, где ошибка стоит не сломанной страницы, а потерянных данных:
// `rsync --delete` без исключения стирает с сервера config.php с паролями, замок установщика
// и обложки, которые загрузили редакторы. Страж читает три файла выкладки и проверяет ровно то,
// что нельзя потерять при следующем запуске скрипта. Это не проверка стиля: каждый assert ниже
// отвечает на вопрос «что произойдёт на боевом сервере, если эту строку убрать».
//
// Сверяется страж с директивами, а не с прозой: литералы `--delete`, `[F]` и `public/index.php`
// стоят в комментариях проверяемых файлов раньше самих правил, и поиск подстрокой по всему файлу
// засчитывал пояснение вместо барьера. Отсюда якорь на начало строки директивы
// (`^[ \t]*<директива>` с флагом `m`) в каждой проверке, а порядок правил сравнивается по
// смещениям этих строк, а не по первым вхождениям подстрок.
final class DeploySafetyTest extends TestCase
{
    private const ROOT = __DIR__ . '/../..';

    // Одиннадцать служебных каталогов, закрытых единой алтернанцией первого правила корневого
    // .htaccess. Список сверяется целиком и в обе стороны: выпавшее имя открывает каталог
    // исходников наружу, а лишнее означает, что эталон отстал от дерева и перестал что-то
    // закреплять. Имя `config` в список не входит — его закрывает отдельное правило того же
    // блока, и сверяется оно своим якорем в проверке ниже.
    private const BLOCKED_NAMES = ['admin', 'apps', 'core', 'docker', 'docs', 'node_modules',
        'scripts', 'sql', 'tests', 'theme', 'vendor'];

    public function testСкриптВыкладкиСуществуетИЗапускается(): void
    {
        $sh = $this->read('scripts/deploy.sh');

        self::assertStringStartsWith('#!/usr/bin/env bash', $sh, 'deploy.sh обязан запускаться сам');
        // Адрес, логин и путь только из окружения: вписанный хостинг в скрипте — это секрет в git
        // и невозможность выложить второй сайт.
        foreach (['CMS_DEPLOY_USER', 'CMS_DEPLOY_HOST', 'CMS_DEPLOY_PATH'] as $var) {
            self::assertMatchesRegularExpression(
                '/:\s*"\$\{' . preg_quote($var, '/') . ':\?/',
                $sh,
                $var . ' обязан читаться через `:?` — запуск без него должен упасть, а не выложить в пустоту'
            );
        }

        // `:?` ловит пустое значение и пропускает относительное, а его rsync считает от домашнего
        // каталога входа: --delete уйдёт чистить соседнее дерево. Проверка ведущего слэша обязана
        // стоять до вызова rsync.
        self::assertMatchesRegularExpression(
            '/case "\$CMS_DEPLOY_PATH" in\s*\n\s*\/\*\)/',
            $sh,
            'deploy.sh обязан отвергать относительный CMS_DEPLOY_PATH до вызова rsync'
        );
    }

    public function testЧетыреПутиНаСервереНеУдаляются(): void
    {
        $sh = $this->read('scripts/deploy.sh');

        // --delete при этом обязателен: без него на сервере остаются удалённые в репозитории
        // PHP-файлы, и следующий прогон читает код прошлой версии. Якорь обязан стоять на строку
        // директивы: `--delete` два раза упоминается в шапке deploy.sh в пояснении, и подстрока
        // по всему файлу оставляла зелёным скрипт, потерявший флаг в RSYNC_OPTS. Граница
        // `(?![\w-])` обязательна: `\b` после `--delete` не годится (дефис — не слововой
        // символ), а без неё этот же образец засчитал бы запретительный `--delete-excluded`.
        self::assertMatchesRegularExpression(
            '/^[ \t]*RSYNC_OPTS=\([^\n]*--delete(?![\w-])[^\n]*\)/m',
            $sh,
            'выкладка обязана чистить устаревшие файлы: флаг --delete должен стоять в самой директиве'
        );

        // …и ровно поэтому в директиве не должно быть `--delete-excluded`: он снимает защиту
        // исключённых файлов, и четыре пути ниже превращаются в приглашение стереть пароли и
        // загрузки. Сверяется запрет по тексту самих директив-массивов, а не по всему файлу:
        // поиск по подстроке краснел, стоило оператору вежливо вписать название запретного флага
        // в комментарий. Порог непустоты обязателен: при нулевом совпадении цикл не выполнился бы
        // ни разу, и проверка молча зеленела бы.
        $directives = [];
        self::assertSame(
            1,
            preg_match_all('/^[ \t]*RSYNC_OPTS=\([^\n]*\)/m', $sh, $directives),
            'в deploy.sh обязана быть ровно одна строка настроек rsync: две означают, что прогон читает не ту'
        );
        foreach ($directives[0] as $line) {
            self::assertStringNotContainsString(
                '--delete-excluded',
                $line,
                'исключённые файлы защищены от удаления: снимающий флаг в директиве запрещён'
            );
        }

        // Исключение обязано быть заякорено на каталог выкладки: `--exclude uploads/` молча
        // совпадёт с любым каталогом одноимённого имени вглубь дерева.
        foreach (['/config.php', '/public/install.lock', '/public/uploads/', '/core/storage/'] as $path) {
            self::assertMatchesRegularExpression(
                '/--exclude=' . preg_quote("'$path'", '/') . '/',
                $sh,
                $path . ' обязан быть в --exclude: --delete стёр бы его с сервера'
            );
        }
    }

    public function testЗондХостингаЗакрытКлючомИУдаляетСебя(): void
    {
        $probe = $this->read('scripts/hosting-probe.php');

        // Пустая строка в репозитории — условие, а не недоработка: секретный ключ не живёт в git,
        // его вписывают в копию файла перед загрузкой. Не пустой — страж падает, и это же
        // означает, что скачанный из репозитория зонд сам по себе безопасен.
        self::assertMatchesRegularExpression('/^\$probeKey = \'\';$/m', $probe, 'в репозитории ключ обязан быть пуст');
        // Сравнение через hash_equals, а не `==`: `==` с магическими хешами пропускает запрос,
        // который никто не авторизовывал.
        self::assertStringContainsString('hash_equals(', $probe, 'ключ сравнивается без утечки по времени');
        self::assertStringContainsString('unlink(__FILE__)', $probe, 'зонд обязан удалиться после ответа');
        // Дамп всех настроек показывает пути, флаги сборки и окружение. Нужен конкретный набор
        // проверяемых значений, и он собирается вручную.
        self::assertStringNotContainsString('phpinfo(', $probe, 'зонд не отдаёт свалку настроек');
        // config.php зонд не читает: на момент проверки его может не быть, а после его создания
        // показывать что-либо из него наружу нельзя.
        self::assertStringNotContainsString("dirname(__DIR__) . '/config.php'", $probe, 'зонд не трогает боевые настройки');
    }

    public function testЗапаснаяРаскладкаЗакрываетСлужебноеДоПереписывания(): void
    {
        $htaccess = $this->read('.htaccess');

        // Порядок правил — не косметика. Apache идёт по списку, и если переписывание в public/
        // стоит раньше блокировки, запрос /core/bootstrap.php совпадёт с существующим файлом,
        // условие !-f его пропустит, и исходники ядра отдадутся наружу. Сравниваются смещения
        // строк-директив, заякоренных на начало строки, а не первые вхождения подстрок: `[F]`
        // стоит в шапке .htaccess в пояснении про порядок, `public/index.php` — в комментарии
        // про маршрутизатор, и оба раньше самих правил. Прежний strpos сравнивал именно эту
        // прозу, из-за чего перенос блокирующих директив под переписывание прогон не краснел.
        $denyAt = $this->offset($htaccess, '/^[ \t]*RewriteRule\b[^\n]*\[F/m');
        $frontAt = $this->offset($htaccess, '/^[ \t]*RewriteRule\b[^\n]*\bpublic\/index\.php\b/m');

        self::assertIsInt($denyAt, 'нет ни одной директивы RewriteRule с флагом [F — служебное открыто');
        self::assertIsInt($frontAt, 'нет директивы переписывания в public/index.php');
        self::assertLessThan($frontAt, $denyAt, 'блокировка служебного обязана предшествовать переписыванию');

        // Список закрытых имён сверяется целиком, а не по четырём словам из одиннадцати:
        // прежнее сравнение пропускало выпадение `tests`, `docs` или `theme`, а это открытый
        // каталог исходников на боевом хостинге. `assertSame` сравнивает множества в обе
        // стороны — лишнее имя в алтернанции тоже красное, оно значит отставший эталон.
        $blocked = $this->line($htaccess, '/^[ \t]*RewriteRule[ \t]+\^\(([^)]*)\)\(\/\|\$\)[ \t]+-[ \t]+\[F,L\]/m');

        self::assertIsString($blocked, 'нет единого правила, закрывающего служебные каталоги одним списком');
        preg_match('/\^\(([^)]*)\)/', $blocked, $names);
        $listed = $names[1] ?? '';
        $actual = explode('|', $listed);
        sort($actual);
        $expected = self::BLOCKED_NAMES;
        sort($expected);
        self::assertSame($expected, $actual, 'список закрытых имён обязан совпадать с эталоном — '
            . 'пропущенное имя открывает каталог исходников наружу');

        // Файл настроек закрывается вторым правилом того же блока: `config` не входит в
        // алтернанцию каталогов выше, поэтому эталон одиннадцати имён его не покрывает и сверен
        // он отдельным якорем по строке этого правила — снова директивой, а не пояснением.
        $configRule = $this->line($htaccess, '/^[ \t]*RewriteRule[ \t]+\^config[^\n]*\[F,L\]/m');
        self::assertIsString($configRule, 'config.php обязан закрываться отдельным правилом с флагом [F,L]');

        // Тормоз повторного прохода: Apache после [L] проходит правила ещё раз с переписанным
        // путём, а %{REQUEST_URI} при этом не меняется, поэтому остановить второй проход может
        // только условие на ссылку правила. Оно относится к следующему за ним правилу, поэтому
        // сверяется соседство строк, а не наличие подстроки: три одинаковых условия в файле
        // оставляли зелёным снятие именно того, что стоит перед переписыванием в index.php.
        // Цена ошибки — подмена вместо цикла: /assets/app.css вторым проходом уехал бы в
        // public/index.php, и вместо стилей отдалась бы разметка.
        self::assertMatchesRegularExpression(
            '/^[ \t]*RewriteCond[ \t]+\$1[ \t]+!\^public\/[ \t]*\r?\n'
            . '[ \t]*RewriteRule[ \t]+\^\(\.\*\)\$[ \t]+public\/index\.php\b/m',
            $htaccess,
            'условие $1 !^public/ обязано стоять непосредственно перед переписыванием в public/index.php: '
            . 'оно тормозит второй проход, и без него запрос /assets/app.css вторым проходом стал бы разметкой'
        );

        // RewriteBase закрепляет корень URL-пространства для per-directory переписывания:
        // Apache строит результат относительно каталога с .htaccess, и на хостинге, где дерево
        // выкладки не совпадает с корнем документ-корня, подстановка public/… склеилась бы с
        // путём к .htaccess вместо корня. Якорь на конец строки не даёт утверждению засчитать
        // упоминание директивы в комментарии вместо самой директивы.
        self::assertMatchesRegularExpression(
            '/^\s*RewriteBase\s+\/\s*$/m',
            $htaccess,
            'RewriteBase / обязателен: в per-directory контексте результат строится от каталога, '
            . 'и без этой строки подстановка public/… склеится с путём к .htaccess вместо корня'
        );
    }

    private function read(string $relative): string
    {
        $path = self::ROOT . '/' . $relative;
        self::assertFileExists($path, $relative . ': файл выкладки обязан существовать');

        $code = file_get_contents($path);
        self::assertIsString($code);

        return $code;
    }

    // Первая строка, подходящая под образец, или null, если такой нет. Нужен текст правила
    // целиком: сверять закрытые имена по одному факту совпадения нельзя.
    private function line(string $text, string $pattern): ?string
    {
        if (preg_match($pattern, $text, $matches) !== 1) {
            return null;
        }

        $matched = $matches[0] ?? null;

        return is_string($matched) ? $matched : null;
    }

    // Смещение первого совпадения в тексте: нужно, чтобы сравнить порядок двух правил,
    // не считаясь с прозой, в которой те же литералы стоят раньше директив.
    private function offset(string $text, string $pattern): ?int
    {
        if (preg_match($pattern, $text, $matches, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }

        $matched = $matches[0] ?? null;

        if (! is_array($matched) || ! isset($matched[1]) || ! is_int($matched[1])) {
            return null;
        }

        return $matched[1];
    }
}
