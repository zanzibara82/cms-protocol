<?php

declare(strict_types=1);

namespace Cms\Tests\guard;

use PHPUnit\Framework\TestCase;

// Заготовку первого шага кормит `setupSeedConfig()` (core/setup-config.php): по каждому ключу из
// `CONFIG_REQUIRED_KEYS` она берёт непустое значение окружения, иначе непустое значение файла,
// иначе непустое значение из `config.sample.php`, а пустой ключ не сидится вовсе. Образец —
// последний источник в этой цепочке, поэтому отсутствующий или пустой ключ в нём означает, что
// экран шага 1 откроется с пустым полем, установщик запишет пустое значение, и сайт отвалится на
// загрузчике уже после установки.
//
// Сверка односторонняя по смыслу: каждый обязательный ключ обязан иметь непустую запись в образце.
// Обратное направление не проверяется нарочно. В образце живут ключи, которые форма шага 1 не
// собирает (раздел 6 спецификации установщика: группа `SMTP_*`, `MAIL_FROM`, `EXTRA_APPS_DIR`,
// `EXTRA_THEME_DIR`), и их отсутствие в `CONFIG_REQUIRED_KEYS` — не нарушение, а свойство: пустой
// `SMTP_HOST` и пустой пароль почты валидны, каталоги фикстур нужны только тестам, а `DB_PASS` не
// входит в список обязательных, потому что пустой пароль базы является законным значением.
final class ConfigSampleKeysTest extends TestCase
{
    public function testКаждыйОбязательныйКлючИмеетНепустуюЗаписьВОбразце(): void
    {
        // Пустой список обязательных ключей — сломанный загрузчик, а не «нарушений нет»: без этих
        // двух строк проверка зелёная и при опустевшем `CONFIG_REQUIRED_KEYS`, и при битом образце.
        self::assertNotSame([], CONFIG_REQUIRED_KEYS, 'Список обязательных ключей пуст — страж сверял бы пустоту');

        /** @var array<string, mixed> $sample */
        $sample = require dirname(__DIR__, 2) . '/config.sample.php';
        self::assertIsArray($sample, 'Образец настроек вернул не массив — страж сверял бы пустоту');
        self::assertNotSame([], $sample, 'Образец настроек пуст — страж сверял бы пустоту');

        $violations = [];

        foreach (CONFIG_REQUIRED_KEYS as $key) {
            if (!array_key_exists($key, $sample)) {
                $violations[] = $key . ': записи нет в config.sample.php';

                continue;
            }

            $value = $sample[$key];

            // Проверка типа стоит раньше приведения: для массива или объекта `(string)` даёт
            // предупреждение, которое обработчик ошибок ядра (core/bootstrap.php) превращает в
            // ErrorException, и вместо имени ключа человек прочитал бы чужой текст.
            if (!is_scalar($value)) {
                $violations[] = $key . ': значение в config.sample.php не скаляр';

                continue;
            }

            // Пустая строка — не значение: `configHasKey()` (core/config-loader.php) считает ключ
            // заданным только при непустой строке, и сид шага 1 такой ключ пропускает.
            if ((string) $value === '') {
                $violations[] = $key . ': запись в config.sample.php пустая, сид шага 1 её пропустит';
            }
        }

        self::assertSame([], $violations, 'Образца настроек не хватит на предзаполнение шага 1 установщика');
    }
}
