// Наполнение демонстрационным контентом: главная страница школы английского языка и страница
// «Витрина блоков», где собраны все виды конструктора по одному разу.
//
// Скрипт — оболочка разработчика, а не часть продукта: он пишет в базу содержимое, которое
// человек потом правит руками в админке. Поэтому по умолчанию он ничего не пишет (режим
// проверки), а существующие секции не трогает: повторный запуск только добавляет недостающие
// ключи. Перезапись — отдельный флаг --reset, и он тоже не удаляет страницы целиком: чистятся
// только секции двух целевых страниц.
//
// Использование:
//   php scripts/seed-demo-content.php [--write] [--reset] [--target=home|vitrina|all]
//
// Секции пишутся через createSection(): правила ядра (уникальный ключ, предел секций, JSON-списки)
// остаются одними и теми же, и наполнитель не может положить в базу строку, которую конструктор
// не принял бы из формы.

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require_once __DIR__ . '/../core/bootstrap.php';

// Отказ в консоли — текстом и с кодом 1: обработчик исключений ядра печатает страницу 500 для
// браузера, и в терминале она читается как мусор.
set_exception_handler(static function (Throwable $error): void {
    fwrite(STDERR, 'Отказ: ' . $error->getMessage() . "\n");
    exit(1);
});

$options = getopt('', ['write', 'reset', 'target:']);

$write = array_key_exists('write', $options);
$reset = array_key_exists('reset', $options);
$target = is_string($options['target'] ?? null) ? (string) $options['target'] : 'all';

if (!in_array($target, ['home', 'vitrina', 'all'], true)) {
    fwrite(STDERR, "Отказ: --target принимает home, vitrina или all.\n");
    exit(1);
}

/**
 * Секция витрины: описание вида для человека и значения его полей. Ключ `key` — якорь секции,
 * он же ключ в базе: повторный запуск узнаёт свою секцию по нему и не создаёт вторую.
 *
 * @param array<string, mixed> $values
 * @return array{key: string, values: array<string, mixed>}
 */
function demoSection(string $key, array $values): array
{
    return ['key' => $key, 'values' => array_merge([
        'kind' => '',
        'layout' => '',
        'anchor' => $key,
        'badge' => '',
        'title' => '',
        'lead_text' => '',
        'note' => '',
        'image' => '',
        'image_alt' => '',
        'buttons' => [],
        'items' => [],
        'settings' => [],
        'visible' => true,
    ], $values)];
}

