/**
 * Запись секций: пропуск уже существующих ключей и, при --reset, чистка целевой страницы.
 *
 * @param list<array{key: string, values: array<string, mixed>}> $sections
 * @return array{created: int, skipped: int, failed: list<string>}
 */
function demoSeed(string $pageId, array $sections, bool $write, bool $reset): array
{
    $stat = ['created' => 0, 'skipped' => 0, 'failed' => []];

    if ($reset && $write) {
        $removed = 0;
        foreach (pageSections($pageId) as $existing) {
            $result = sectionDelete((string) $existing['id']);
            if ($result['ok']) {
                $removed++;
            }
        }

        echo '  чистка: удалено секций — ', $removed, "\n";
    }

    $existingKeys = [];
    foreach (pageSections($pageId) as $existing) {
        $existingKeys[(string) $existing['sec_key']] = true;
    }

    foreach ($sections as $section) {
        if (isset($existingKeys[$section['key']])) {
            $stat['skipped']++;
            echo '  = ', $section['key'], ' (уже есть)', "\n";

            continue;
        }

        if (!$write) {
            $stat['created']++;
            echo '  + ', $section['key'], ' [', (string) $section['values']['kind'], ']', "\n";

            continue;
        }

        $result = createSection($pageId, $section['values'], nowUtc());

        if (!$result['ok']) {
            $stat['failed'][] = $section['key'] . ': ' . $result['error'];
            echo '  ! ', $section['key'], ' — ', $result['error'], "\n";

            continue;
        }

        $stat['created']++;
        echo '  + ', $section['key'], ' [', (string) $section['values']['kind'], ']', "\n";
    }

    return $stat;
}

$vitrina = findPage('vitrina-blokov');
$mode = $write ? 'запись' : 'проверка (в базу ничего не пишется)';

echo "Демонстрационный контент: режим — $mode.\n";
echo 'Сброс секций перед записью: ', $reset ? 'да' : 'нет', ".\n\n";

$total = ['created' => 0, 'skipped' => 0, 'failed' => []];

if ($target === 'home' || $target === 'all') {
    echo "Главная страница (page_id = ''):\n";
    $stat = demoSeed(PAGES_HOME_ID, demoHomeSections(), $write, $reset);
    $total['created'] += $stat['created'];
    $total['skipped'] += $stat['skipped'];
    $total['failed'] = array_merge($total['failed'], $stat['failed']);
    echo "\n";
}

if ($target === 'vitrina' || $target === 'all') {
    if ($vitrina === null) {
        echo "Витрина блоков: страница с адресом vitrina-blokov не найдена — пропущена.\n\n";
    } else {
        echo "Витрина блоков (/vitrina-blokov):\n";
        $stat = demoSeed((string) $vitrina['id'], demoVitrinaSections(), $write, $reset);
        $total['created'] += $stat['created'];
        $total['skipped'] += $stat['skipped'];
        $total['failed'] = array_merge($total['failed'], $stat['failed']);
        echo "\n";
    }
