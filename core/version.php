<?php

declare(strict_types=1);

// Версия ядра. Приложение устанавливается только если его requiresCore не выше этого числа.
// 1.2.0 — слой страниц (sql/0002_pages.sql): главная и адресные страницы собираются секциями.
const CORE_VERSION = '1.2.0';

// Безопасные версии PHP после обновления 21 октября 2026 года. Выпуск 8.3.36 закрывает
// CVE-2026-109618 и CVE-2026-109619: повреждение состояния движка при аварийном выходе
// (bailout), заявлена возможность удалённого выполнения кода без аутентификации. Частичных
// мер защиты нет — обновление движка единственный способ закрыть дыру, поэтому список ниже
// это условие безопасной работы, а не формальность.
//
// Значение — минимальная исправленная версия ветки. null значит «исправленной версии нет»:
// ветка 8.1 достигла конца поддержки и обновлений безопасности больше не получает.
// Ветки новее 8.5 в списке отсутствуют: о них у нас нет данных, и объявлять их уязвимыми
// без оснований нельзя.
const CORE_PHP_PATCHED = [
    '8.1' => null,
    '8.2' => '8.2.35',
    '8.3' => '8.3.36',
    '8.4' => '8.4.27',
    '8.5' => '8.5.12',
];

/**
 * Состояние PHP по обновлению безопасности:
 * 'ok' — мы на исправленной версии своей ветки или новее;
 * 'old' — версия ветки старше исправленной (дыра открыта);
 * 'none' — исправленной версии у ветки нет: поддержка закончилась, обновлений не будет;
 * 'unknown' — ветки нет в списке: данных у нас нет, и выдумывать их нельзя.
 */
function corePhpSecurityState(string $version = PHP_VERSION): string
{
    $branch = substr($version, 0, 3);

    if (!array_key_exists($branch, CORE_PHP_PATCHED)) {
        return 'unknown';
    }

    $patched = CORE_PHP_PATCHED[$branch];

    if ($patched === null) {
        return 'none';
    }

    return version_compare($version, $patched, '>=') ? 'ok' : 'old';
}

/**
 * Что именно делать: формулировка для админки и зонда хостинга. Пустая строка означает
 * «называть нечего» — состояние 'ok'.
 */
function corePhpSecurityHint(string $version = PHP_VERSION): string
{
    $branch = substr($version, 0, 3);
    $patched = CORE_PHP_PATCHED[$branch] ?? null;

    return match (corePhpSecurityState($version)) {
        'ok' => '',
        'old' => 'нужно не ниже ' . (string) $patched
            . ' — обновление 21 октября 2026 года закрывает CVE-2026-109618 и CVE-2026-109619'
            . ' (удалённое выполнение кода без аутентификации); частичных мер нет, нужно обновление',
        'none' => 'поддержка ветки закончилась, исправлений для неё больше не будет'
            . ' — переходите на 8.2.35 или новее',
        default => 'ветки нет в списке известных версий — данных о ней у нас нет',
    };
}
