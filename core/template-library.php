/**
 * Список для экрана: без состава блоков (он нужен только применению) плюс число блоков — по нему
 * человек понимает, сколько места займёт шаблон.
 *
 * @return list<array{key: string, name: string, category: string, categoryName: string, description: string, layout: string, sections: int}>
 */
function templateLibraryAll(): array
{
    $rows = [];

    foreach (templateLibraryCatalog() as $key => $template) {
        $rows[] = [
            'key' => $key,
            'name' => $template['name'],
            'category' => $template['category'],
            'categoryName' => TEMPLATE_LIBRARY_CATEGORIES[$template['category']] ?? $template['category'],
            'description' => $template['description'],
            'layout' => $template['layout'],
            'sections' => count($template['sections']),
        ];
    }

    return $rows;
}

/**
 * Шаблон по ключу. Ключ приходит из адреса и из формы, поэтому сверяется с каталогом: чужой ключ
 * означает «такого шаблона нет», а не «применить что попало».
 *
 * @return array{key: string, name: string, category: string, description: string, layout: string, sections: list<array<string, mixed>>}|null
 */
function templateLibraryFind(string $key): ?array
{
    $catalog = templateLibraryCatalog();

    if (!array_key_exists($key, $catalog)) {
        return null;
    }

    return ['key' => $key] + $catalog[$key];
}

/**
 * Фильтр каталога по категории: пустая категория — весь список. Неизвестная категория даёт
 * пустой список, а не весь каталог: экран с фильтром не должен показывать «всё», когда фильтр
 * ничего не нашёл.
 *
 * @return list<array{key: string, name: string, category: string, categoryName: string, description: string, layout: string, sections: int}>
 */
function templateLibraryFiltered(string $category): array
{
    $rows = templateLibraryAll();

    if ($category === '') {
        return $rows;
    }

    return array_values(array_filter($rows, static fn (array $row): bool => $row['category'] === $category));
}

/**
 * Применение шаблона к странице. По умолчанию блоки **добавляются** к существующим: шаблон — это
 * заготовка, а не замена, и потерять уже собранную страницу одним нажатием нельзя. Замена идёт
 * только с явным подтверждением и убирает прежние блоки в корзину — оттуда их можно вернуть.
 *
 * Всё одной транзакцией: половина шаблона на странице хуже, чем ничего. Блоки ставятся через
 * createSection(), поэтому предел секций, уникальность якорей и ревизия проверяются теми же
 * правилами, что и при ручной сборке.
 *
 * @return array{ok: bool, error: string, created: int, pageId: string, notice: string}
 */
function templateLibraryApply(string $pageId, string $key, bool $replace = false, ?DateTimeImmutable $now = null): array
{
    $template = templateLibraryFind($key);

    if ($template === null) {
        return ['ok' => false, 'error' => 'Такого шаблона нет — обновите список.', 'created' => 0, 'pageId' => $pageId, 'notice' => ''];
    }

    if ($pageId !== PAGES_HOME_ID && pageById($pageId) === null) {
        return ['ok' => false, 'error' => 'Страница исчезла — обновите список.', 'created' => 0, 'pageId' => $pageId, 'notice' => ''];
    }

    $existing = pageSections($pageId);

    // Предел проверяется до вставки: частичное применение упёрлось бы в него посреди шаблона.
    $willHave = count($template['sections']) + ($replace ? 0 : count($existing));

    if ($willHave > PAGES_SECTIONS_LIMIT) {
        return [
            'ok' => false,
            'error' => 'На странице станет больше ' . PAGES_SECTIONS_LIMIT . ' блоков — уберите лишние или выберите замену содержимого.',
            'created' => 0,
            'pageId' => $pageId,
            'notice' => '',
        ];
    }

    $created = 0;

    try {
        tx(static function () use ($pageId, $template, $replace, $existing, $now, &$created): void {
            if ($replace) {
                foreach ($existing as $section) {
                    $trashed = trashSection((string) $section['id'], ['operation' => 'system', 'comment' => 'Страница заменена шаблоном «' . $template['name'] . '»']);

                    if (($trashed['ok'] ?? false) !== true) {
                        throw new RuntimeException((string) ($trashed['error'] ?? 'Не удалось убрать прежние блоки.'));
                    }
                }
            }

            foreach ($template['sections'] as $section) {
                $result = createSection($pageId, $section, $now, ['operation' => 'system', 'comment' => 'Шаблон «' . $template['name'] . '»']);

                if (($result['ok'] ?? false) !== true) {
                    throw new RuntimeException((string) ($result['error'] ?? 'Блок шаблона не добавился.'));
                }

                $created++;
            }
        });
    } catch (Throwable $error) {
        logError('templates.apply_failed', ['key' => $key, 'pageId' => $pageId, 'message' => $error->getMessage()]);

        // Откат вернул страницу к прежнему виду: created обнуляется, чтобы вызывающий не показывал
        // «добавлено 3 блока», которых нет.
        return ['ok' => false, 'error' => $error->getMessage(), 'created' => 0, 'pageId' => $pageId, 'notice' => ''];
    }

    logInfo('templates.applied', ['key' => $key, 'pageId' => $pageId, 'created' => $created, 'replace' => $replace]);

    return ['ok' => true, 'error' => '', 'created' => $created, 'pageId' => $pageId, 'notice' => 'template_applied'];
}
