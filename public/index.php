<?php

declare(strict_types=1);

// Встроенный сервер PHP отдаёт существующие файлы сам, только если сценарий-маршрутизатор
// вернул false. Без этой строки под `php -S` ни `/assets/app.css`, ни `/setup.php` не открылись бы:
// каждый запрос уходил бы в маршрутизатор и заканчивался 404. На Apache то же делает правило
// `RewriteCond %{REQUEST_FILENAME} !-f` в `public/.htaccess`.
if (PHP_SAPI === 'cli-server') {
    $requested = (string) parse_url((string) ($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH);
    $file = __DIR__ . $requested;
    // Замок установщика — не раздача: он обязан отвечать 404, а не скачиваться.
    if ($requested !== '/' && is_file($file) && pathinfo($file, PATHINFO_EXTENSION) !== 'lock') {
        return false;
    }
}

require dirname(__DIR__) . '/core/bootstrap.php';

securityHeaders();

// Пока схема ядра не создана, любой маршрут упрётся в отсутствующую таблицу и даст пустой ответ.
// Человек первым делом открывает главную — значит фронт-контроллер объясняет, что делать, и ведёт
// в установщик. /setup.php — отдельный файл, он обслуживается напрямую и сюда не заходит.
if (!isSiteInstalled()) {
    respond(
        503,
        partial('not-installed'),
        [
            'Content-Type' => 'text/html; charset=utf-8',
            'X-Robots-Tag' => 'noindex, nofollow',
            // Пакет V, находка 3 аудита просмотра: экран собирается `partial()` и не проходит через
            // `render()`, поэтому запрет кэширования прописан здесь явно. До `startSession()` лимитер
            // PHP заголовки не присылал бы вовсе, а подсказка подменяется сразу после установки.
            'Cache-Control' => 'no-store',
        ]
    );
}

// Домашняя страница, вход и выход живут в ядре: registerCoreRoutes() регистрирует их вместо
// временной строки задачи 5.
registerCoreRoutes();

// Маршруты разделов регистрирует ядро на каждом запросе — сам файл маршрутов «не появляется»: без
// этой строки адресов приложений в реестре нет вовсе, и админка не показала бы ни ленту раздела,
// ни 404 выключенного раздела. Порядок фиксирован: маршруты ядра, маршруты разделов, разбор запроса.
// Сессию поднимает dispatch(): маршрут известен только там, и адреса без сессии (приёмник
// счётчика) отвечают вовсе без cookie.
registerAppRoutes();

dispatch();
