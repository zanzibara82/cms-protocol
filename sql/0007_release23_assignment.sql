-- RELEASE 2.3 (часть C): назначение макета на типе контента. Файл только дополняет схему:
-- строки tbl_content_type остаются на месте, значения существующих колонок не меняются.
--
-- Макет живёт в JSON-настройках типа (`settings`), а не отдельной колонкой: настроек у типа со
-- временем станет больше (шаблон карточки, колонки списка, правила SEO), и каждая новая
-- потребовала бы ALTER. Одного поля хватает, чтобы приоритет назначения из §14 (объект → тип →
-- умолчание) работал и для архивов пользовательских типов.
--
-- Значение по умолчанию — пустой JSON-объект, а НЕ '{}' строкой в PHP: пустая настройка означает
-- «макет не назначен», и решение принимает следующая ступень приоритета. Если бы умолчанием стоял
-- 'default', каждый тип перебивал бы значение по умолчанию сайта и лендинг сайта стал бы невозможен.
--
-- Повторяемость обеспечивает журнал миграций (tbl_app_migration), а не сам файл: applyApp() пишет
-- строку сразу после применения, тестовая база ведёт тот же журнал. Держит
-- CoreMigrationIdempotencyTest.

ALTER TABLE tbl_content_type
  ADD COLUMN settings TEXT NULL AFTER archived_at;
